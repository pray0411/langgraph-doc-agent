# Pray installer (no admin required).
#
# Installs the app into %LOCALAPPDATA%\Programs\Pray, creates Start Menu and
# Desktop shortcuts, and registers an "Apps & Features" entry so it can be
# uninstalled normally.
#
# Usage:
#   powershell -NoProfile -ExecutionPolicy Bypass -File install.ps1
#   powershell -NoProfile -ExecutionPolicy Bypass -File install.ps1 -InstallDir D:\tmp\pray -NoShortcuts
#
# Notes:
# - The target directory must be user-writable: the app stores .env / data /
#   generated next to Pray.exe (that is how the in-app API-key setup persists).
# - All user-facing text is ASCII so this script runs correctly under both
#   Windows PowerShell 5.1 and PowerShell 7 regardless of code page.

[CmdletBinding()]
param(
    [string]$InstallDir = (Join-Path $env:LOCALAPPDATA 'Programs\Pray'),
    [switch]$NoShortcuts,
    [switch]$NoLaunch
)

$ErrorActionPreference = 'Stop'
$src = $PSScriptRoot
$appExe = Join-Path $InstallDir 'Pray.exe'

Write-Host ""
Write-Host "============================================" -ForegroundColor Cyan
Write-Host "  Pray installer" -ForegroundColor Cyan
Write-Host "============================================" -ForegroundColor Cyan
Write-Host "  Source : $src"
Write-Host "  Target : $InstallDir"
Write-Host ""

if (-not (Test-Path (Join-Path $src 'Pray.exe'))) {
    Write-Host "[ERROR] Pray.exe not found next to this script." -ForegroundColor Red
    Write-Host "        Run install.bat from the extracted package folder."
    exit 1
}

# ---------- 1. stop a running instance (files would be locked) ----------
$running = Get-Process -Name 'Pray' -ErrorAction SilentlyContinue
if ($running) {
    Write-Host "[1/5] Stopping running Pray (files are locked while it runs)..."
    $running | Stop-Process -Force -ErrorAction SilentlyContinue
    Start-Sleep -Milliseconds 800
} else {
    Write-Host "[1/5] No running instance."
}

# ---------- 2. copy files ----------
Write-Host "[2/5] Copying files..."
New-Item -ItemType Directory -Force -Path $InstallDir | Out-Null
# 绝不复制的东西：
#   - 安装器/卸载器自身（目标目录会重新生成卸载器）
#   - **.env**：含用户的 API Key。分发包里带上它就是把密钥发给所有人
#   - 运行时数据（data / generated / logs / index）：属于用户私有数据，
#     只应在目标目录里新建空目录，不该从"打包源"继承
$skip = @(
    'install.bat', 'install.ps1', 'uninstall.bat', 'uninstall.ps1',
    '.env', 'data', 'generated', 'logs', 'index', '__pycache__'
)
Get-ChildItem -Path $src -Force | Where-Object { $skip -notcontains $_.Name } | ForEach-Object {
    Copy-Item -Path $_.FullName -Destination $InstallDir -Recurse -Force
}
foreach ($d in @('data', 'generated', 'logs')) {
    New-Item -ItemType Directory -Force -Path (Join-Path $InstallDir $d) | Out-Null
}

# ---------- 3. shortcuts ----------
if (-not $NoShortcuts) {
    Write-Host "[3/5] Creating shortcuts..."
    $ws = New-Object -ComObject WScript.Shell
    $startMenu = Join-Path $env:APPDATA 'Microsoft\Windows\Start Menu\Programs\Pray.lnk'
    $lnk = $ws.CreateShortcut($startMenu)
    $lnk.TargetPath = $appExe
    $lnk.WorkingDirectory = $InstallDir
    $lnk.Description = 'Pray - local AI Agent'
    $lnk.Save()

    $desktop = Join-Path ([Environment]::GetFolderPath('Desktop')) 'Pray.lnk'
    $lnk2 = $ws.CreateShortcut($desktop)
    $lnk2.TargetPath = $appExe
    $lnk2.WorkingDirectory = $InstallDir
    $lnk2.Description = 'Pray - local AI Agent'
    $lnk2.Save()
} else {
    Write-Host "[3/5] Shortcuts skipped (-NoShortcuts)."
}

# ---------- 4. uninstall script + Apps & Features entry ----------
Write-Host "[4/5] Registering uninstaller..."
$uninstallScript = @'
# Pray uninstaller (generated by install.ps1)
$ErrorActionPreference = 'SilentlyContinue'
$dir = Split-Path -Parent $MyInvocation.MyCommand.Path
Get-Process -Name 'Pray' | Stop-Process -Force
Start-Sleep -Milliseconds 500
# remove shortcuts
Remove-Item (Join-Path $env:APPDATA 'Microsoft\Windows\Start Menu\Programs\Pray.lnk') -Force
Remove-Item (Join-Path ([Environment]::GetFolderPath('Desktop')) 'Pray.lnk') -Force
# remove registry entry
Remove-Item 'HKCU:\Software\Microsoft\Windows\CurrentVersion\Uninstall\Pray' -Recurse -Force
# keep user data (generated/ data/) unless -PurgeData is given
if ($args -contains '-PurgeData') {
    Remove-Item $dir -Recurse -Force
} else {
    Get-ChildItem -Path $dir -Force | Where-Object { $_.Name -notin @('.env','generated','data') } |
        Remove-Item -Recurse -Force
    Write-Host "Kept user data: .env, generated\, data\  (pass -PurgeData to remove everything)"
}
Write-Host "Pray uninstalled."
'@
Set-Content -Path (Join-Path $InstallDir 'uninstall.ps1') -Value $uninstallScript -Encoding UTF8

$uninstallBat = @'
@echo off
powershell -NoProfile -ExecutionPolicy Bypass -File "%~dp0uninstall.ps1" %*
pause
'@
Set-Content -Path (Join-Path $InstallDir 'uninstall.bat') -Value $uninstallBat -Encoding ASCII

$version = '0.0.0'
if (Test-Path (Join-Path $src 'VERSION')) { $version = (Get-Content (Join-Path $src 'VERSION') -Raw).Trim() }
$regKey = 'HKCU:\Software\Microsoft\Windows\CurrentVersion\Uninstall\Pray'
New-Item -Path $regKey -Force | Out-Null
Set-ItemProperty -Path $regKey -Name 'DisplayName' -Value 'Pray'
Set-ItemProperty -Path $regKey -Name 'DisplayVersion' -Value $version
Set-ItemProperty -Path $regKey -Name 'DisplayIcon' -Value $appExe
Set-ItemProperty -Path $regKey -Name 'InstallLocation' -Value $InstallDir
Set-ItemProperty -Path $regKey -Name 'Publisher' -Value 'pray0411'
Set-ItemProperty -Path $regKey -Name 'UninstallString' -Value "powershell -NoProfile -ExecutionPolicy Bypass -File `"$(Join-Path $InstallDir 'uninstall.ps1')`""
Set-ItemProperty -Path $regKey -Name 'NoModify' -Value 1 -Type DWord
Set-ItemProperty -Path $regKey -Name 'NoRepair' -Value 1 -Type DWord

Write-Host "[5/5] Done."
Write-Host ""
Write-Host "  Installed to : $InstallDir"
Write-Host "  Version      : $version"
if (-not $NoShortcuts) {
    Write-Host "  Shortcuts    : Start Menu + Desktop"
}
Write-Host ""
Write-Host "  First run: fill in your API key in the settings panel, then it persists"
Write-Host "             to .env next to Pray.exe (no need to type it again)."
Write-Host ""

if (-not $NoLaunch) {
    $answer = Read-Host "Launch Pray now? [Y/n]"
    if ($answer -eq '' -or $answer -match '^[Yy]') {
        Start-Process -FilePath $appExe -WorkingDirectory $InstallDir
    }
}
